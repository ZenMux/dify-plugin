def _pdf_bytes(text):
    objs = ["<</Type/Catalog/Pages 2 0 R>>", "<</Type/Pages/Kids[3 0 R]/Count 1>>",
            "<</Type/Page/Parent 2 0 R/MediaBox[0 0 400 200]/Contents 4 0 R/Resources<</Font<</F1 5 0 R>>>>>>",
            None, "<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>"]
    stream = f"BT /F1 28 Tf 40 100 Td ({text}) Tj ET".encode()
    out, offsets = bytearray(b"%PDF-1.4\n"), []
    for i, obj in enumerate(objs, 1):
        offsets.append(len(out))
        body = (b"<</Length %d>>stream\n" % len(stream) + stream + b"\nendstream") if obj is None else obj.encode()
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1) + b"".join(b"%010d 00000 n \n" % o for o in offsets)
    out += b"trailer\n<</Size %d/Root 1 0 R>>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)
    return bytes(out)


def _run_media_tools(cmds, out):
    import subprocess
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        for cmd in cmds:
            subprocess.run([c.format(tmp=tmp) for c in cmd], check=True, capture_output=True)
        return Path(tmp, out).read_bytes()


def _close(expected, answer):
    """The answer reads back the random code, allowing a misread character or a collapsed double letter.

    A blind guess cannot get there; an exact match wrongly failed gpt-4o and claude-sonnet-4.5 on images.
    """
    import difflib
    words = re.findall(r"[A-Z0-9]+", answer.upper()) or [""]
    return max(difflib.SequenceMatcher(None, expected, w).ratio() for w in words) >= 0.6


def input_samples():
    """One sample per modality whose answer cannot be guessed (a random code to read back), as Dify content.

    Returns {modality: (content, question, check)}. Images and videos are rendered with `ffmpeg`
    (drawtext), audio with macOS `say` + `afconvert`; a modality is missing if its tool is.
    Solid colours were tried first and wrongly failed 7 models that read text in images fine.
    """
    import random
    import shutil
    from dify_plugin.entities.model.message import (AudioPromptMessageContent, DocumentPromptMessageContent,
                                                    ImagePromptMessageContent, VideoPromptMessageContent)
    rnd = random.SystemRandom()
    code = lambda: "".join(rnd.choice("ACDEFHJKMNPRTWXY34679") for _ in range(6))  # noqa: E731
    b64 = lambda data: base64.b64encode(data).decode()  # noqa: E731
    reads = lambda c: lambda a: _close(c, a)  # noqa: E731
    question = "What is the code printed after CODE in the {}? Reply with the code only."
    pdf_code, image_code, video_code = code(), code(), code()
    digits = "".join(rnd.choice("23456789") for _ in range(4))
    samples = {"file": (DocumentPromptMessageContent(format="pdf", mime_type="application/pdf", filename="probe.pdf",
                                                     base64_data=b64(_pdf_bytes(f"CODE {pdf_code}"))),
                        question.format("PDF"), reads(pdf_code))}
    if shutil.which("ffmpeg"):
        def render(text, out, *args):
            return _run_media_tools([["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", f"color=c=white:s=480x120:d=2:r=5",
                                      "-vf", f"drawtext=text='CODE {text}':fontsize=56:fontcolor=black:x=20:y=30",
                                      *args, f"{{tmp}}/{out}"]], out)
        samples["image"] = (ImagePromptMessageContent(format="png", mime_type="image/png",
                                                      base64_data=b64(render(image_code, "i.png", "-frames:v", "1"))),
                            question.format("image"), reads(image_code))
        samples["video"] = (VideoPromptMessageContent(format="mp4", mime_type="video/mp4", filename="probe.mp4",
                                                      base64_data=b64(render(video_code, "v.mp4", "-pix_fmt", "yuv420p",
                                                                             "-movflags", "+faststart"))),
                            question.format("video"), reads(video_code))
    if shutil.which("say") and shutil.which("afconvert"):
        wav = _run_media_tools([["say", "-r", "120", "-o", "{tmp}/a.aiff", ", ".join(digits)],
                                ["afconvert", "-f", "WAVE", "-d", "LEI16@22050", "{tmp}/a.aiff", "{tmp}/a.wav"]], "a.wav")
        samples["audio"] = (AudioPromptMessageContent(format="wav", mime_type="audio/wav", base64_data=b64(wav)),
                            "Which digits are spoken in the audio? Reply with the digits only.",
                            lambda a: _close(digits, re.sub(r"\D", "", a)))
    return samples


THINKING_PROMPT = [{"role": "user", "content": "A bat and a ball cost 1.10 in total. The bat costs 1.00 more "
                    "than the ball. How much is the ball? Answer with just the number."}]


def probe_thinking_off(mid, key):
    """Which `thinking` value turns thinking off on this Claude model?

    Per Anthropic's per-model table most models take {"type": "disabled"}, Sonnet 5.5 takes
    {"type": "between_tools"} instead, and some (Opus 5.5, Fable) cannot turn it off at all.
    A value counts only if it is accepted AND the reply has no thinking block, because ZenMux
    silently ignores "disabled" on some always-on models instead of rejecting it.
    """
    for kind in ("disabled", "between_tools"):
        status, body = _post("/api/anthropic/v1/messages", {"model": mid, "max_tokens": 1024, "thinking": {"type": kind},
                                                            "messages": THINKING_PROMPT}, key, anthropic=True)
        if status == 200 and not any(b.get("type") == "thinking" for b in body.get("content") or []):
            return kind
    return "always_on"


def _ask_with_file(m, probe, content, question, key, fmt=None):
    """Send one file + question exactly the way the plugin's route converter builds it; return the answer."""
    from dify_plugin.entities.model.message import TextPromptMessageContent
    parts, mid, proto = [TextPromptMessageContent(data=question), content], m["id"], protocol_of(m["id"])
    if proto == "google":
        from google.genai import types
        from models.llm.google import ZenMuxGoogleLargeLanguageModel
        try:
            client = ZenMuxGoogleLargeLanguageModel._client({"api_key": key})
            resp = client.models.generate_content(
                model=mid, config=types.GenerateContentConfig(max_output_tokens=4096), contents=[types.Content(
                    role="user", parts=[types.Part.from_text(text=question),
                                        types.Part.from_bytes(data=base64.b64decode(content.base64_data),
                                                              mime_type=content.mime_type)])])
            return 200, resp.text or ""
        except Exception as exc:
            return getattr(exc, "code", 0) or 0, str(exc)[:200]
    if proto == "anthropic":
        from models.llm.anthropic_llm import ZenMuxAnthropicLargeLanguageModel as cls
        body = {"model": mid, "max_tokens": 4096,
                "messages": [{"role": "user", "content": cls._build_content_blocks(cls.__new__(cls), parts)}]}
        if probe.get("thinking_off") in ("disabled", "between_tools"):
            body["thinking"] = {"type": probe["thinking_off"]}
        status, resp = _post("/api/anthropic/v1/messages", body, key, anthropic=True)
        return status, "".join(b.get("text", "") for b in resp.get("content") or []) if status == 200 else resp
    from models.llm.openai import ZenMuxOpenAICCLargeLanguageModel as cls
    formats = {INPUT_KIND_OF[content.type]: fmt} if fmt else None
    body = {"model": mid, "max_tokens": 4096, "messages": [{"role": "user", "content": [cls._content_part(p, formats) for p in parts]}]}
    if probe.get("effort"):
        body["reasoning_effort"] = probe["effort"][0]
    status, resp = _post("/api/v1/chat/completions", body, key)
    return status, (resp["choices"][0].get("message") or {}).get("content") or "" if status == 200 else resp


def probe_inputs(m, probe, key, samples):
    """Does the model really use each input modality the catalog lists, sent the way the plugin sends it?

    Each sample has an answer that cannot be guessed (random colour, code or digits), so a model
    that accepts the file but ignores it fails. Modalities the route cannot deliver are not probed.
    """
    sys.path.insert(0, str(ROOT))
    from models.llm.openai import INPUT_FORMAT_CANDIDATES
    results, formats = {}, {}
    for modality in sorted(set(m["input"]) & ROUTE_INPUTS[protocol_of(m["id"])]):
        if modality not in samples:
            results[modality] = "skipped: no local tool to make the sample"
            continue
        content, question, check = samples[modality]
        # On the OpenAI-compatible route the part format differs per upstream: try each candidate.
        candidates = INPUT_FORMAT_CANDIDATES.get(modality, [None]) if protocol_of(m["id"]) == "openai" else [None]
        tried = []
        for fmt in candidates:
            # A declared input must work reliably: two correct answers in a row, transient errors retried.
            # (muse-spark-1.3-contributor read the audio about half the time and passed a single try.)
            correct = 0
            for _attempt in range(4):
                status, answer = _ask_with_file(m, probe, content, question, key, fmt)
                if status in (0, 429) or status >= 500:
                    continue
                if status != 200 or not check(answer):
                    break
                correct += 1
                if correct == 2:
                    break
            if correct == 2:
                results[modality] = "ok"
                if fmt:
                    formats[modality] = fmt
                break
            outcome = (f"error:{status} {re.sub(r'\s*\(request_id[^)]*\)', '', str(answer))[:100]}" if status != 200
                       else f"mismatch: {answer.strip()[:50]!r}")
            tried.append(f"{fmt}: {outcome}" if fmt and len(candidates) > 1 else outcome)
            results[modality] = " | ".join(tried)
    return results, formats


def is_transient(result):
    return bool(re.match(r"error:(0|429|5\d\d)\b", result or "")) and " | " not in result


def probe_model(m, key, checks, old, samples):
    """Run the `basic` checks (alive, tools, parameters) and/or the `inputs` checks (file modalities)."""
    result = {"checked_at": today()}
    if "basic" in checks:
        result.update(probe_basics(m, key))
    alive = result.get("alive", old.get("alive")) is not False
    if "inputs" in checks and alive:
        if m["type"] == "llm":
            result["inputs"], result["input_formats"] = probe_inputs(m, {**old, **result}, key, samples)
        elif "image" in m["input"]:
            result["image"] = probe_image(m, key)
    return result


def probe_basics(m, key):
    mid, proto, result = m["id"], protocol_of(m["id"]), {}
    if m["type"] == "text-embedding":
        status, body = _post("/api/v1/embeddings", {"model": mid, "input": ["alpha", "beta", "gamma"]}, key)
        result["batch_ok"] = status == 200 and len(body.get("data", [])) == 3
    if m["type"] != "llm":
        return result
    # The catalog keeps listing some retired models; a plain request tells us.
    status, body = _post("/api/v1/chat/completions", {
        "model": mid, "max_tokens": 16, "messages": [{"role": "user", "content": "hi"}]}, key)
    dead = status in (400, 404, 500) and re.search(r"deprecated|no longer available|does not exist|not found", str(body), re.I)
    result["alive"] = not dead
    if dead:
        result["error"] = re.sub(r"\s*\(request_id[^)]*\)", "", str(body))[:200]
        return result
    if proto == "openai":
        status, body = _post("/api/v1/chat/completions", {
            "model": mid, "max_tokens": 512, "tools": WEATHER_TOOL,
            "messages": [{"role": "user", "content": "What's the weather in Paris right now? Use the tool."}],
        }, key)
        if status == 200:
            calls = (body["choices"][0].get("message") or {}).get("tool_calls")
            result["tools"] = "called" if calls else "ignored"
        else:
            result["tools"] = f"rejected:{status}"
        if mid.startswith("openai/") and m.get("reasoning"):
            ok = []
            for effort in ALL_EFFORTS:
                status, body = _post("/api/v1/chat/completions", {
                    "model": mid, "max_tokens": 16, "reasoning_effort": effort,
                    "messages": [{"role": "user", "content": "hi"}],
                }, key)
                if status == 200 or (status == 400 and "max_output_tokens" in str(body)):
                    ok.append(effort)
            result["effort"] = ok
    elif proto == "anthropic":
        msgs = [{"role": "user", "content": "hi"}]
        status, _ = _post("/api/anthropic/v1/messages", {"model": mid, "max_tokens": 16, "temperature": 0.5, "messages": msgs}, key, anthropic=True)
        result["temperature"] = status == 200
        status, _ = _post("/api/anthropic/v1/messages", {"model": mid, "max_tokens": 1024, "thinking": {"type": "adaptive"}, "messages": msgs}, key, anthropic=True)
        result["adaptive"] = status == 200
        if m.get("reasoning"):
            result["thinking_off"] = probe_thinking_off(mid, key)
    return result


def cmd_probe(args):
    key = os.environ.get("ZENMUX_PROBE_API_KEY")
    if not key:
        sys.exit("set ZENMUX_PROBE_API_KEY (a PAYG key is recommended; probes cost well under $1 in total)")
    snapshot, overrides, probes = load_inputs()
    models, _ = included_models(snapshot, overrides, {})  # re-probe retired models too
    if args.only:
        models = [m for m in models if any(re.search(p, m["id"]) for p in args.only)]
    elif not args.all:
        models = [m for m in models if m["id"] not in probes]
    print(f"probing {len(models)} models ({', '.join(args.checks)}) ...", file=sys.stderr)
    data = load_json(PROBES, {"models": {}})
    samples = input_samples() if "inputs" in args.checks else {}
    old = data["models"]
    with concurrent.futures.ThreadPoolExecutor(args.workers) as pool:
        for m, res in zip(models, pool.map(lambda x: probe_model(x, key, args.checks, old.get(x["id"], {}), samples), models)):
            prev = old.get(m["id"], {})
            merged = {**prev, **res}
            if res.get("alive"):
                merged.pop("error", None)
            # A rate limit or outage says nothing about support: keep an earlier "ok" (and its format).
            for k, v in (res.get("inputs") or {}).items():
                if is_transient(v) and (prev.get("inputs") or {}).get(k) == "ok":
                    merged["inputs"][k] = "ok"
                    if k in (prev.get("input_formats") or {}):
                        merged["input_formats"][k] = prev["input_formats"][k]
            data["models"][m["id"]] = merged
            print(f"  {m['id']:45} {json.dumps({k: v for k, v in res.items() if k != 'checked_at'})}", file=sys.stderr)
    data["models"] = dict(sorted(data["models"].items()))
    PROBES.write_text(json.dumps(data, indent=1) + "\n")
    print(f"reported cost: ${sum(SPENT):.4f} over {len(SPENT)} requests (Vertex requests not included)", file=sys.stderr)


