def file_stem(model_id, taken):
    stem = model_id.split("/", 1)[1]
    if stem in taken:
        stem = model_id.replace("/", "-")
    taken.add(stem)
    return stem


def price_block(price, with_output=True):
    def fmt(v):
        return f"{float(v):.4f}".rstrip("0").rstrip(".") if v is not None else "0"

    block = {"input": fmt(price["input"])}
    if with_output:
        block["output"] = fmt(price.get("output"))
    return {**block, "unit": "0.000001", "currency": "USD"}


def llm_features(m, probe):
    proto = protocol_of(m["id"])
    # Probe "called" is conclusive; "rejected" means the endpoint errors on tool requests;
    # "ignored" (answered in text) or no probe falls back to the website parameter list.
    tools, known = probe.get("tools"), m.get("params") or []
    if tools == "called":
        has_tools = True
    elif tools and tools.startswith("rejected"):
        has_tools = False
    else:
        has_tools = proto != "openai" or not known or "tools" in known
    feats = ["tool-call", "multi-tool-call", "stream-tool-call"] if has_tools else []
    if m.get("reasoning"):
        feats.append("agent-thought")
    feats += [MODAL_FEATURES[k] for k in verified_inputs(m, probe)]
    removed = set(m.get("features_remove") or [])
    return [f for f in feats + list(m.get("features_add") or []) if f not in removed]


def build_llm(m, probe):
    context = m.get("context") or 0
    max_out = m.get("max_output") or min(context or DEFAULT_MAX_TOKENS, DEFAULT_MAX_TOKENS)
    if context:
        max_out = min(max_out, context)
    proto = protocol_of(m["id"])
    if proto == "anthropic":
        rules = anthropic_rules(m, max_out, probe)
    elif proto == "google":
        rules = gemini_rules(m, max_out)
    elif m["id"].startswith("openai/"):
        rules = openai_rules(m, max_out, probe)
    else:
        rules = generic_rules(m, max_out)
    if m.get("reasoning") and proto in HIDE_REASONING_ROUTES:
        rules.append(HIDE_REASONING)
    removed = set(m.get("params_remove") or [])
    rules = [r for r in rules if r["name"] not in removed]
    return {
        "model": m["id"], "label": i18n(m["name"], m["name"]), "model_type": "llm",
        "features": llm_features(m, probe),
        "model_properties": {"mode": "chat", "context_size": context},
        "parameter_rules": rules, "pricing": price_block(m["price"]),
    }


def retrieval_features(m, probe):
    """Dify (>= 1.11) treats embedding/rerank models listing `vision` as multimodal and sends images.

    The catalog's input modalities are not trusted on their own: `vision` needs a passing image probe.
    """
    feats = ["vision"] if "image" in m["input"] and probe.get("image") == "ok" else []
    removed = set(m.get("features_remove") or [])
    kept = [f for f in feats + list(m.get("features_add") or []) if f not in removed]
    return {"features": kept} if kept else {}


def build_embedding(m, probe):
    max_chunks = m.get("max_chunks") or (2048 if probe.get("batch_ok", True) else 1)
    return {
        "model": m["id"], "label": i18n(m["name"], m["name"]), "model_type": "text-embedding",
        **retrieval_features(m, probe),
        "model_properties": {"context_size": m.get("context") or 8192, "max_chunks": max_chunks},
        "pricing": price_block(m["price"], with_output=False),
    }


def build_rerank(m, probe):
    return {"model": m["id"], "label": i18n(m["name"], m["name"]), "model_type": "rerank",
            **retrieval_features(m, probe),
            "model_properties": {"context_size": m.get("context") or 8192}}


BUILDERS = {"llm": build_llm, "text-embedding": build_embedding, "rerank": build_rerank}


def build_all():
    snapshot, overrides, probes = load_inputs()
    models, dropped = included_models(snapshot, overrides, probes)
    order = {p: i for i, p in enumerate(overrides.get("provider_order") or [])}
    files = {}
    for mtype, folder in MODEL_DIRS.items():
        group = [m for m in models if m["type"] == mtype]
        group.sort(key=lambda m: (order.get(m["id"].split("/")[0], len(order)), "-" + (m.get("publish_time") or ""), m["id"]))
        taken = set()
        for m in sorted(group, key=lambda m: m["id"]):
            stem = file_stem(m["id"], taken)
            files[folder / f"{stem}.yaml"] = GENERATED_HEADER + dump_yaml(BUILDERS[mtype](m, probes.get(m["id"], {})))
        if group:
            files[folder / "_position.yaml"] = GENERATED_HEADER + dump_yaml([m["id"] for m in group])
    thinking_off = {m["id"]: probes[m["id"]]["thinking_off"] for m in models
                    if protocol_of(m["id"]) == "anthropic" and (probes.get(m["id"]) or {}).get("thinking_off")}
    files[THINKING_FILE] = json.dumps(dict(sorted(thinking_off.items())), indent=1) + "\n"
    formats = {}
    for m in models:
        probe = probes.get(m["id"]) or {}
        verified = {k: v for k, v in (probe.get("input_formats") or {}).items() if k in verified_inputs(m, probe)}
        if protocol_of(m["id"]) == "openai" and verified:
            formats[m["id"]] = dict(sorted(verified.items()))
    files[INPUT_FORMATS_FILE] = json.dumps(dict(sorted(formats.items())), indent=1) + "\n"
    return files, models, dropped, snapshot


def existing_files():
    out = {}
    for folder in MODEL_DIRS.values():
        if folder.exists():
            out.update({p: p.read_text() for p in folder.glob("*.yaml")})
    for path in (THINKING_FILE, INPUT_FORMATS_FILE):
        if path.exists():
            out[path] = path.read_text()
    return out


def summarize(old_text, new_text):
    old, new = yaml.safe_load(old_text) or {}, yaml.safe_load(new_text) or {}
    if isinstance(old, list) or isinstance(new, list):
        return ["order changed"]
    notes = []
    o_ctx, n_ctx = (old.get("model_properties") or {}).get("context_size"), (new.get("model_properties") or {}).get("context_size")
    if o_ctx != n_ctx:
        notes.append(f"context {o_ctx}→{n_ctx}")
    op, np_ = old.get("pricing") or {}, new.get("pricing") or {}
    for k in ("input", "output"):
        if k in np_ and (op.get(k) is None or float(op.get(k)) != float(np_[k])):
            notes.append(f"price.{k} {op.get(k)}→{np_[k]}")
    of, nf = set(old.get("features") or []), set(new.get("features") or [])
    if of != nf:
        notes.append("features " + " ".join([f"+{f}" for f in sorted(nf - of)] + [f"-{f}" for f in sorted(of - nf)]))
    orules = {r["name"] for r in old.get("parameter_rules") or []}
    nrules = {r["name"] for r in new.get("parameter_rules") or []}
    if orules != nrules:
        notes.append("params " + " ".join([f"+{r}" for r in sorted(nrules - orules)] + [f"-{r}" for r in sorted(orules - nrules)]))
    return notes or ["formatting/details"]


REASONING_PARAMS = {"enable_thinking", "exclude_reasoning_tokens", "reasoning_effort", "reasoning_budget", "verbosity",
                    "include_thoughts", "thinking_mode", "thinking_budget", "thinking_level"}
TOOL_FEATURES = {"tool-call", "multi-tool-call", "stream-tool-call"}


def removal_evidence(kind, name, m, probe):
    """Why a model may lose a parameter/feature it shipped with, from catalog or probe data (None = unexplained)."""
    inputs = probe.get("inputs") or {}
    modality = {v: k for k, v in MODAL_FEATURES.items()}.get(name)
    if kind == "feature" and name in TOOL_FEATURES and probe.get("tools") and probe["tools"] != "called":
        return f"tool probe: {probe['tools']}"
    if kind == "feature" and modality:
        if modality not in m["input"]:
            return "catalog no longer lists the input"
        if modality not in ROUTE_INPUTS[protocol_of(m["id"])]:
            return "route cannot deliver it"
        if modality in inputs and inputs[modality] != "ok" and not is_transient(inputs[modality]):
            return f"input probe: {inputs[modality][:60]}"
    if (kind == "feature" and name == "agent-thought" or kind == "param" and name in REASONING_PARAMS) and not m.get("reasoning"):
        return "catalog: not a reasoning model"
    if kind == "param" and name == "temperature" and probe.get("temperature") is False:
        return "probe: non-default temperature rejected"
    if kind == "param" and name == "reasoning_budget" and probe.get("adaptive"):
        return "probe: adaptive thinking (no budget)"
    if kind == "param" and name == "enable_thinking" and probe.get("thinking_off") == "always_on":
        return "probe: thinking cannot be turned off"
    return None


def release_removals(files, base, models, probes):
    """User-facing parameters and features a model shipped in `base` (a git ref) and would lose now.

    Losing one breaks saved Dify workflows silently (the SDK drops unknown parameters), so each removal
    needs catalog/probe evidence (removal_evidence) or an `accepted_removals` entry with a reason.
    """
    import subprocess
    accepted = (yaml.safe_load(OVERRIDES.read_text()) or {}).get("accepted_removals") or {}
    by_id = {m["id"]: m for m in models}
    out = []
    for path, text in files.items():
        if path.name.startswith("_") or path.suffix != ".yaml":
            continue
        shown = subprocess.run(["git", "show", f"{base}:{path.relative_to(ROOT).as_posix()}"], cwd=ROOT, capture_output=True, text=True)
        if shown.returncode != 0:
            continue
        old, new = yaml.safe_load(shown.stdout) or {}, yaml.safe_load(text) or {}
        mid = new.get("model")
        m, probe, ok = by_id.get(mid), probes.get(mid) or {}, accepted.get(mid) or {}
        names = lambda d: {r["name"] for r in d.get("parameter_rules") or []}  # noqa: E731
        lost = [("param", n) for n in sorted(names(old) - names(new)) if n not in (ok.get("params") or [])]
        lost += [("feature", f) for f in sorted(set(old.get("features") or []) - set(new.get("features") or []))
                 if f not in (ok.get("features") or [])]
        unexplained = [f"{k} {n}" for k, n in lost if not (m and removal_evidence(k, n, m, probe))]
        if unexplained:
            out.append((mid, unexplained))
    return sorted(out, key=lambda x: str(x[0]))


def model_id_of(text):
    data = yaml.safe_load(text)
    return data.get("model") if isinstance(data, dict) else None


def cmd_sync(args):
    files, models, dropped, snapshot = build_all()
    probes = load_json(PROBES, {}).get("models", {})
    old = existing_files()
    added, removed, changed = [], [], []
    for path, text in files.items():
        if path.name.startswith("_"):
            continue
        if path not in old:
            added.append(model_id_of(text) or path.name)
        elif old[path] != text:
            changed.append((model_id_of(text), summarize(old[path], text)))
    removed = [model_id_of(t) or p.name for p, t in old.items() if p not in files]
    if not args.dry_run:
        for path in old:
            if path not in files:
                path.unlink()
        for path, text in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

    counts = {t: sum(1 for m in models if m["type"] == t) for t in MODEL_DIRS}
    lines = [f"## Model sync (catalog snapshot {snapshot.get('fetched_at')})", "",
             f"Included: {counts}. Excluded: {len(dropped)}.", ""]
    for title, items in (("Added", sorted(filter(None, added))), ("Removed", sorted(filter(None, removed)))):
        if items:
            lines += [f"### {title} ({len(items)})", ", ".join(f"`{i}`" for i in items), ""]
    if changed:
        lines += [f"### Changed ({len(changed)})"] + [f"- `{mid}`: {'; '.join(n)}" for mid, n in sorted(changed, key=lambda x: str(x[0]))] + [""]
    tiered = [m["id"] for m in models if m.get("tiered")]
    if tiered:
        lines += [f"### Tiered pricing ({len(tiered)}) - YAML holds the base tier; Dify records the per-request `usage.cost` where ZenMux returns it",
                  ", ".join(f"`{i}`" for i in tiered), ""]
    claude = [(m["id"], (probes.get(m["id"]) or {}).get("thinking_off", "not probed")) for m in models
              if protocol_of(m["id"]) == "anthropic" and m.get("reasoning")]
    if claude:
        lines += ["### Claude thinking off-switch (probe) - check against Anthropic's per-model table "
                  "(platform.claude.com/docs/en/build-with-claude/thinking-troubleshooting)"]
        lines += [f"- `{mid}`: {res}" for mid, res in claude] + [""]
    unverified = []
    for m in models:
        probe = probes.get(m["id"]) or {}
        if m["type"] != "llm":
            if "image" in m["input"] and probe.get("image") != "ok":
                unverified.append((m["id"], f"image: {probe.get('image', 'not probed')}"))
            continue
        route = protocol_of(m["id"])
        for k in MODAL_FEATURES:
            if k in m["input"] and k not in verified_inputs(m, probe):
                why = (probe.get("inputs") or {}).get(k, "not probed") if k in ROUTE_INPUTS[route] else f"not deliverable on the {route} route"
                unverified.append((m["id"], f"{k}: {why}"))
    if unverified:
        lines += [f"### Inputs listed in the catalog but not verified ({len(unverified)}) - shipped without them (re-probe `--checks inputs`)"]
        lines += [f"- `{mid}` {res}" for mid, res in unverified] + [""]
    removals = release_removals(files, args.base, models, probes)
    if removals:
        lines += [f"### Removed vs `{args.base}` and not accepted ({len(removals)}) - fix, or add to `accepted_removals` with a reason"]
        lines += [f"- `{mid}`: {', '.join(lost)}" for mid, lost in removals] + [""]
    lines += ["### Excluded"] + [f"- `{m['id']}`: {r}" for m, r in sorted(dropped, key=lambda x: x[0]["id"])]
    print("\n".join(lines))


def cmd_check(args):
    files, models, *_ = build_all()
    if args.base:
        removals = release_removals(files, args.base, models, load_json(PROBES, {}).get("models", {}))
        if removals:
            print(f"user-facing removals vs {args.base} (fix, or add to accepted_removals with a reason):\n  "
                  + "\n  ".join(f"{mid}: {', '.join(lost)}" for mid, lost in removals))
            sys.exit(1)
    old = existing_files()
    drift = sorted({str(p.relative_to(ROOT)) for p in set(files) ^ set(old)} |
                   {str(p.relative_to(ROOT)) for p in files if p in old and old[p] != files[p]})
    if drift:
        print("YAMLs are out of sync with catalog/ (run `sync`):\n  " + "\n  ".join(drift))
        sys.exit(1)
    print(f"ok: {len(files)} generated files match catalog/")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("fetch")
    p = sub.add_parser("probe")
    p.add_argument("--only", nargs="*", help="regex filters on model id")
    p.add_argument("--all", action="store_true", help="re-probe models that already have results")
    p.add_argument("--workers", type=int, default=4)
    p.add_argument("--checks", nargs="+", choices=["basic", "inputs"], default=["basic", "inputs"],
                   help="basic: alive, tools, parameters; inputs: whether listed file modalities really work")
    s = sub.add_parser("sync")
    s.add_argument("--dry-run", action="store_true")
    s.add_argument("--base", default="origin/main", help="last released state to diff user-facing removals against")
    c = sub.add_parser("check")
    c.add_argument("--base", help="also fail on unaccepted user-facing removals vs this git ref (e.g. origin/main)")
    args = ap.parse_args()
    {"fetch": cmd_fetch, "probe": cmd_probe, "sync": cmd_sync, "check": cmd_check}[args.cmd](args)


if __name__ == "__main__":
    main()
