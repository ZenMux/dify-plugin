# ── IO helpers ───────────────────────────────────────────────────────────────

def http_json(url, body=None, headers=None, timeout=60):
    data = json.dumps(body).encode() if body is not None else None
    # The website endpoint rejects the default urllib User-Agent.
    base_headers = {"Content-Type": "application/json", "User-Agent": "zenmux-dify-plugin-sync/1.0 (+curl compatible)"}
    req = urllib.request.Request(url, data=data, headers={**base_headers, **(headers or {})})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.load(resp)


def load_json(path, default):
    return json.loads(path.read_text()) if path.exists() else default


def dump_yaml(data) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000)


def today():
    return datetime.date.today().isoformat()


