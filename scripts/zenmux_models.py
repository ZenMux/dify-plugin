def first_tier(pricings, key):
    """Base-tier price: the tier whose conditions start lowest (or has none)."""
    def start(tier):
        conds = tier.get("conditions") or {}
        return min((float(c.get("gte") or 0) for c in conds.values() if isinstance(c, dict)), default=0.0)

    tiers = (pricings or {}).get(key) or []
    return min(tiers, key=start)["value"] if tiers else None


def cmd_fetch(_args):
    official = http_json(OFFICIAL_URL)["data"]
    if len(official) < 50:
        sys.exit(f"official catalog returned only {len(official)} models; refusing to overwrite snapshot")
    try:
        frontend = {x["slug"]: x for x in http_json(FRONTEND_URL)["data"]}
    except Exception as exc:  # enrichment only; the sync falls back to overrides/defaults
        print(f"warning: website metadata unavailable ({exc}); max_output/params will fall back", file=sys.stderr)
        frontend = {}

    models = []
    for m in official:
        mtype = TYPE_BY_OUTPUT.get(tuple(m.get("output_modalities") or []))
        if not mtype:
            continue
        f = frontend.get(m["id"], {})
        pricings = m.get("pricings") or {}
        models.append({
            "id": m["id"],
            "name": m.get("display_name") or m["id"],
            "type": mtype,
            "publish_time": m.get("publish_time"),
            "input": m.get("input_modalities") or [],
            "context": m.get("context_length"),
            "reasoning": (m.get("capabilities") or {}).get("reasoning"),
            "price": {
                "input": first_tier(pricings, "prompt"),
                "output": first_tier(pricings, "completion"),
                "cache_read": first_tier(pricings, "input_cache_read"),
            } if first_tier(pricings, "prompt") is not None else None,
            "tiered": any(len(v) > 1 for v in pricings.values()),
            "max_output": f.get("max_completion_tokens"),
            "params": sorted(p for p in (f.get("supported_parameters") or "").split(",") if p),
            "website_reasoning": f.get("supports_reasoning"),
        })
    models.sort(key=lambda x: x["id"])
    CATALOG_DIR.mkdir(exist_ok=True)
    SNAPSHOT.write_text(json.dumps({"fetched_at": today(), "source": OFFICIAL_URL, "models": models}, indent=1, ensure_ascii=False) + "\n")
    counts = {t: sum(1 for m in models if m["type"] == t) for t in MODEL_DIRS}
    print(f"snapshot: {len(models)} in-scope models {counts} (official catalog total {len(official)})")


# ── shared model resolution ──────────────────────────────────────────────────

def load_inputs():
    if not SNAPSHOT.exists():
        sys.exit("catalog/snapshot.json missing; run `fetch` first")
    snapshot = load_json(SNAPSHOT, {})
    overrides = yaml.safe_load(OVERRIDES.read_text()) or {}
    probes = load_json(PROBES, {}).get("models", {})
    return snapshot, overrides, probes


def protocol_of(model_id: str) -> str:
    # Must stay in sync with models/llm/zenmux.py::protocol_of
    if model_id.startswith("anthropic/"):
        return "anthropic"
    if model_id.startswith("google/gemini-"):
        return "google"
    return "openai"


def resolve(m, overrides, probes):
    """Merge catalog entry with manual data. Returns (model, exclusion_reason)."""
    excl = overrides.get("exclude") or {}
    m = {**m, **((overrides.get("manual") or {}).get(m["id"]) or {}), **((overrides.get("models") or {}).get(m["id"]) or {})}
    if m["id"] in (excl.get("ids") or {}):
        return m, excl["ids"][m["id"]]
    probe = probes.get(m["id"]) or {}
    if probe.get("alive") is False:
        return m, f"retired upstream (probe {probe.get('checked_at')}): {probe.get('error')}"
    if any(m["id"].endswith(s) for s in excl.get("id_suffixes") or []):
        return m, "free model"
    price = m.get("price")
    if m["type"] != "rerank":
        if not price or price.get("input") is None:
            return m, "no pricing in catalog (verify via /management/generation, then add under `manual`)"
        if excl.get("zero_priced") and not price.get("input") and not price.get("output"):
            return m, "zero-priced (free)"
    if m.get("reasoning") is None:
        m["reasoning"] = bool(m.get("website_reasoning"))
    return m, None


def included_models(snapshot, overrides, probes):
    kept, dropped = [], []
    for raw in snapshot["models"]:
        m, reason = resolve(raw, overrides, probes)
        (dropped if reason else kept).append((m, reason))
    return [m for m, _ in kept], dropped


